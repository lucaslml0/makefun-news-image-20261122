// Entry point for the make.fun "Sum up 22 November's world news in one
// image" bounty.
//
// The artwork (entry.png) is generated deterministically by draw_entry.py
// (Python + PIL, DejaVu fonts, no network access). Running this script
// regenerates entry.png from scratch and copies it to the output
// directory required by the competition:
//
//   MAKEFUN_OUTPUT_DIR=/output node main.ts   ->  /output/entry.png
//
// If MAKEFUN_OUTPUT_DIR is not set, the output directory defaults to
// /output. Running the script twice produces byte-identical PNGs.
import { copyFileSync, existsSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, "draw_entry.py");
const source = join(here, "entry.png");

if (!existsSync(script)) {
  console.error("draw_entry.py not found next to main.ts");
  process.exit(1);
}

// Regenerate the artwork deterministically.
execFileSync("python3", [script], { stdio: "inherit", cwd: here });

if (!existsSync(source)) {
  console.error("entry.png was not generated by draw_entry.py");
  process.exit(1);
}

const outDir = process.env.MAKEFUN_OUTPUT_DIR || "/output";
mkdirSync(outDir, { recursive: true });

const dest = join(outDir, "entry.png");
copyFileSync(source, dest);
console.log(`Wrote ${dest}`);
